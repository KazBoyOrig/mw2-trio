"""Generate PE32 winmm proxy stubs, preserving named and ordinal exports.

Adapted from mw2_coop tools/gen_winmm_proxy.py (MIT; see LICENSE).
This reads the installed Windows DLL; it never executes downloaded code.
"""
import hashlib
import json
from pathlib import Path
import struct
import sys


def exports(path):
    data = Path(path).read_bytes()
    if data[:2] != b'MZ':
        raise ValueError('not a PE image')
    pe = struct.unpack_from('<I', data, 0x3C)[0]
    if data[pe:pe + 4] != b'PE\0\0':
        raise ValueError('invalid PE signature')
    machine, nsec = struct.unpack_from('<HH', data, pe + 4)
    opt = pe + 24
    optsz = struct.unpack_from('<H', data, pe + 20)[0]
    if machine != 0x14C or struct.unpack_from('<H', data, opt)[0] != 0x10B:
        raise ValueError('need x86 PE32 winmm.dll')
    er, esize = struct.unpack_from('<II', data, opt + 96)
    secs = [struct.unpack_from('<IIII', data, opt + optsz + 40 * i + 8)
            for i in range(nsec)]

    def r2o(rva):
        for vsz, va, rsz, rp in secs:
            if va <= rva < va + max(vsz, rsz):
                result = rva - va + rp
                if result >= len(data) or rva - va >= rsz:
                    raise ValueError('RVA has no file data')
                return result
        raise ValueError(f'unmapped RVA {rva:#x}')

    def string(rva):
        offset = r2o(rva)
        return data[offset:data.index(b'\0', offset)].decode('ascii')

    eoff = r2o(er)
    base, count, nnam, af, an, ao = struct.unpack_from('<IIIIII', data, eoff + 16)
    names = {}
    for i in range(nnam):
        name_rva = struct.unpack_from('<I', data, r2o(an) + 4 * i)[0]
        index = struct.unpack_from('<H', data, r2o(ao) + 2 * i)[0]
        names.setdefault(index, []).append(string(name_rva))
    result = []
    for index in range(count):
        fn = struct.unpack_from('<I', data, r2o(af) + 4 * index)[0]
        if fn:
            result.append({'ordinal': base + index, 'names': names.get(index, []),
                           'forwarder': string(fn) if er <= fn < er + esize else None})
    return result, hashlib.sha256(data).hexdigest()


def main():
    source = Path(sys.argv[1])
    root = Path(__file__).resolve().parents[1]
    rows, digest = exports(source)
    src = root / 'src'
    src.mkdir(parents=True, exist_ok=True)
    asm = ['# Generated by tools/gen_winmm32_proxy.py; x86 tail jumps.', '\t.text']
    defs = ['LIBRARY winmm.dll', 'EXPORTS']
    hdr = ['/* Generated from the Windows PE32 export table. */', '#pragma once',
           f'#define WINMM_EXPORT_COUNT {len(rows)}',
           'typedef struct { unsigned short ordinal; const char *name; } proxy_export;',
           'static const proxy_export winmm_exports[WINMM_EXPORT_COUNT] = {']
    for slot, row in enumerate(rows):
        symbol = f'winmm_proxy_{slot}'
        asm.extend([f'\t.globl _{symbol}', '\t.p2align 4', f'_{symbol}:',
                    f'\tjmp *_winmm_real+{4 * slot}'])
        if row['names']:
            for n, name in enumerate(row['names']):
                # The first name preserves its original ordinal. Aliases share the stub.
                suffix = f" @{row['ordinal']}" if n == 0 else ''
                defs.append(f'\t{name}={symbol}{suffix}')
            cname = json.dumps(row['names'][0])
        else:
            defs.append(f"\tordinal_{row['ordinal']}={symbol} @{row['ordinal']} NONAME")
            cname = 'NULL'
        hdr.append(f"\t{{{row['ordinal']}, {cname}}},")
    defs.extend(['\tMw2TrioGuardCurrent=bootstrap_guard_current',
                 '\tMw2TrioGuardFileW=bootstrap_guard_file',
                 '\tMw2TrioProxyExportCount=bootstrap_export_count'])
    hdr.append('};')
    for name, lines in [('winmm32_stubs.S', asm), ('winmm32.def', defs), ('winmm32_exports.h', hdr)]:
        (src / name).write_text('\n'.join(lines) + '\n', encoding='ascii', newline='\n')
    (root / 'system-export-manifest.json').write_text(json.dumps({
        'source': '%SystemRoot%/SysWOW64/winmm.dll', 'sha256': digest,
        'machine': '0x014C', 'exports': rows}, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(rows)} x86 export stubs; source SHA-256 {digest}')


if __name__ == '__main__':
    main()
